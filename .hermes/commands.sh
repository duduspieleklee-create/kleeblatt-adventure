# Project Commands
# Quick access to all development commands

# === Development ===

# Start development server (hot-reload enabled)
npm install && npm run dev

# === Build ===

# Build for production
npm run build

# Preview production build
npm run preview

# === Testing ===

# Run tests
npm run test

# === GitHub Actions ===

# Lint (prettier)
npm install && npm run lint

# === Convert to PRs ===

# After making changes, create PR to Gala Games repository:
# git push origin main
# Create PR at https://github.com/gala-games/kleinanzeigen-adventure
